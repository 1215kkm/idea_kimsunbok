async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="ko-KR-SunHiNeural")
    ap.add_argument("--rate", default="+5%")
    ap.add_argument("--out", default="guide-voices")
    a = ap.parse_args()
    import edge_tts

    os.makedirs(a.out, exist_ok=True)
    for n, (vid, sid, text) in enumerate(LINES, 1):
        path = os.path.join(a.out, f"{vid}__{sid}.mp3")
        await edge_tts.Communicate(text, a.voice, rate=a.rate).save(path)
        print(f"{n:2d}/{len(LINES)}  {path}")
    print(f"\n완료: {a.out}/ 폴더의 mp3 {len(LINES)}개를 「음성 파일 한꺼번에 올리기」로 한 번에 넣고 「저장하기」를 누르세요.")


if __name__ == "__main__":
    asyncio.run(main())
